// ------------------------------------------------------------------ static server
let serverDown = false;
const requests = [];
function startServer() {
  return new Promise((resolve) => {
    const srv = http.createServer((req, res) => {
      requests.push(req.url);
      if (serverDown) { req.socket.destroy(); return; }
      let p = decodeURIComponent(req.url.split('?')[0].split('#')[0]);
      if (p.includes('..')) { res.writeHead(400); res.end(); return; }
      let f = path.join(SITE, p);
      if (p.endsWith('/')) f = path.join(f, 'index.html');
      fs.stat(f, (err, st) => {
        if (!err && st.isDirectory()) { res.writeHead(301, { Location: p + '/' }); res.end(); return; }
        if (err) {
          fs.readFile(path.join(SITE, '404.html'), (e2, b) => { res.writeHead(404, { 'Content-Type': MIME['.html'] }); res.end(e2 ? 'not found' : b); });
          return;
        }
        res.writeHead(200, { 'Content-Type': MIME[path.extname(f).toLowerCase()] || 'application/octet-stream', 'Content-Length': st.size, 'Cache-Control': 'no-cache' });
        if (req.method === 'HEAD') { res.end(); return; }
        fs.createReadStream(f).pipe(res);
      });
    });
    srv.listen(0, '127.0.0.1', () => resolve(srv));
  });
}

// ------------------------------------------------------------------ book data (as shipped)
function loadBook() {
  const src = fs.readFileSync(path.join(SITE, 'app', 'data', 'book.js'), 'utf8');
  const ctx = { window: {} };
  vm.runInNewContext(src, ctx);
  return { book: ctx.window.ELO_BOOK, build: ctx.window.ELO_BUILD, src };
}

// If the book has no chapters or no stage test yet (authors still writing), the feature tests
// use a copy augmented with clearly synthetic content so every feature is still exercised.
function augment(book) {
  const b = JSON.parse(JSON.stringify(book));
  const notes = [];
  const exIds = Object.keys(b.exercises);
  if (!b.chapters.length) {
    notes.push('book has no chapters yet: reader test uses a synthetic chapter');
    b.chapters.push({ n: 1, slug: 'synthetic', title: 'Synthetic Test Chapter', subtitle: 'Generated by test_app.js', stage: '400–600', part: 1, skills: ['opening-traps'],
      objectives: ['Test objective.'], next_game: 'Test next game.', exercises: [],
      html: '<p>Synthetic chapter for automated tests.</p><h2 id="ch-01-1">Section</h2>' +
        '<figure class="diagram" data-fen="r1bqkb1r/pppp1ppp/2n2n2/4p2Q/2B1P3/8/PPPP1PPP/RNB1K1NR w KQkq - 4 4" data-orientation="white" data-arrows="h5f7 c4f7" data-red="" data-blue="" data-squares="f7" data-lastmove=""><div class="board-wrap" role="img" aria-label="Chess diagram"></div><figcaption>Test diagram.</figcaption></figure>' +
        '<div class="line" data-start="rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1"><p class="moves"><span class="mn">1.</span><span class="mv" data-fen="rnbqkbnr/pppppppp/8/8/4P3/8/PPPP1PPP/RNBQKBNR b KQkq - 0 1" data-uci="e2e4">e4</span> <span class="mv" data-fen="rnbqkbnr/pppp1ppp/8/4p3/4P3/8/PPPP1PPP/RNBQKBNR w KQkq - 0 2" data-uci="e7e5">e5</span></p></div>' +
        '<aside class="box box-key"><p class="box-head"><span class="box-label">Key idea</span></p><p>Test.</p></aside>' });
  }
  if (!Object.values(b.sets).some((s) => s.is_test) && exIds.length) {
    notes.push('book has no stage test yet: stage-test mode uses a synthetic test set');
    const ids = [];
    exIds.slice(0, 5).forEach((id, i) => {
      const nid = `T1-${String(90 + i)}`;
      b.exercises[nid] = Object.assign({}, b.exercises[id], { id: nid, set: 'T1', label: `T1.${90 + i}` });
      ids.push(nid);
    });
    b.sets.T1 = { title: 'Stage 1 Test (synthetic)', ids, is_test: true };
  }
  return { book: b, notes };
}

// ------------------------------------------------------------------ harness
const results = [];
let failures = 0;
let currentPage = null;
const ONLY = process.env.ONLY ? new RegExp(process.env.ONLY, 'i') : null;
async function test(name, fn) {
  if (ONLY && !ONLY.test(name)) return;
  const t0 = Date.now();
  try {
    const note = await fn();
    results.push({ name, ok: true, ms: Date.now() - t0, note });
    console.log(`PASS  ${name}${note ? '  — ' + note : ''}  (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
  } catch (e) {
    failures++;
    results.push({ name, ok: false, ms: Date.now() - t0, err: e });
    if (currentPage) await currentPage.screenshot({ path: path.join(SHOTS, 'FAILED-' + name.replace(/[^a-z0-9]+/gi, '-').slice(0, 60) + '.png') }).catch(() => {});
    console.log(`FAIL  ${name}\n      ${String(e && e.message || e).split('\n').slice(0, 6).join('\n      ')}`);
  }
}
function assert(c, msg) { if (!c) throw new Error(msg || 'assertion failed'); }
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
function ymd(d) { return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`; }
function addDays(iso, n) { const d = new Date(iso + 'T12:00:00'); d.setDate(d.getDate() + n); return ymd(d); }
const TODAY = ymd(new Date());

function watchErrors(page, bucket) {
  page.on('console', (m) => { if (m.type() === 'error') bucket.push('console: ' + m.text()); });
  page.on('pageerror', (e) => bucket.push('pageerror: ' + e.message));
  page.on('requestfailed', (r) => { const u = r.url(); if (!u.startsWith('data:') && !u.startsWith('blob:')) bucket.push('requestfailed: ' + u + ' ' + (r.failure() && r.failure().errorText)); });
  page.on('request', (r) => { const u = r.url(); if (!/^(https?:\/\/127\.0\.0\.1|data:|blob:)/.test(u)) bucket.push('external request: ' + u); });
}

async function shot(page, name) {
  await page.waitForTimeout(250);
  await page.screenshot({ path: path.join(SHOTS, name + '.png') });
}

async function state(page) { return page.evaluate(() => JSON.parse(localStorage.getItem('elo-blueprint') || '{}')); }

async function goto(page, base, hash) {
  const url = base + 'app/#' + hash;
  if (page.url() === url) await page.reload(); else await page.goto(url);
  await page.waitForSelector('#main .page, #main .solve-page', { timeout: 15000 });
}

async function sq(page, square, mobile) {
  const loc = page.locator(`.gameboard rect[data-sq="${square}"]`).first();
  if (mobile) await loc.tap(); else await loc.click();
}

async function playSan(page, fen, san, mobile, promoPiece) {
  const c = new Chess(fen);
  const m = c.move(san);
  await sq(page, m.from, mobile);
  await sq(page, m.to, mobile);
  if (m.promotion) {
    await page.locator(`.promo-btn[data-promo="${promoPiece || m.promotion}"]`).click();
  }
  return m;
}

async function pieceAt(page, square) {
  const loc = page.locator(`.gameboard use[data-at="${square}"]`);
  return (await loc.count()) ? loc.first().getAttribute('data-piece') : null;
}

