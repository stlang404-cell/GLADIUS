// Converts the GLADIUS wordmark (Cinzel, SIL OFL) to vector outlines so the logo
// SVGs are fully self-contained. Writes src/art/logoWordmark.ts.
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const load = (w) => {
  const b = readFileSync(`node_modules/@fontsource/cinzel/files/cinzel-latin-${w}-normal.woff`);
  return opentype.parse(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength));
};
const heavy = load(900);
const medium = load(700);
function text(font, str, size, tracking) {
  // Lay out glyph by glyph using each glyph's advance (robust for spaces).
  let x = 0;
  const parts = [];
  for (const ch of str) {
    const g = font.charToGlyph(ch);
    let d = g.getPath(x, size, size).toPathData(2);
    if (d.includes('NaN')) d = g.getPath(Math.round(x * 10) / 10 + 0.01, size, size).toPathData(2);
    if (d.includes('NaN')) d = g.getPath(0, size, size).toPathData(2).replace(/(-?\d+\.?\d*) (-?\d+\.?\d*)/g, (_m, a, b) => `${(+a + x).toFixed(2)} ${b}`);
    if (d && !d.includes('NaN')) parts.push(d);
    const adv = Number.isFinite(g.advanceWidth) ? g.advanceWidth : font.unitsPerEm * 0.3;
    x += (adv / font.unitsPerEm) * size + tracking;
  }
  return { d: parts.join(' '), width: x - tracking, top: 0, bottom: size };
}
const title = text(heavy, 'GLADIUS', 100, 6);
const tag = text(medium, 'THE ETERNAL CHESS EMPIRE', 22, 7.5);
writeFileSync('src/art/logoWordmark.ts', `// Generated by scripts/build-wordmark.mjs from Cinzel (SIL Open Font License). Do not edit.
export const WORDMARK = ${JSON.stringify(title)};
export const TAGLINE = ${JSON.stringify(tag)};
`);
